const STORAGE_KEY  = 'dc_language';
const DEFAULT_LANG = 'english';

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [langValue, setLangValue] = useState(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return LANGUAGES.find(l => l.value === saved) ? saved : DEFAULT_LANG;
  });

  const setLanguage = useCallback((value) => {
    if (LANGUAGES.find(l => l.value === value)) {
      setLangValue(value);
      localStorage.setItem(STORAGE_KEY, value);
    }
  }, []);

  const langObj = LANGUAGES.find(l => l.value === langValue) || LANGUAGES[0];

  /** Translate a key -- falls back to English, then the key itself */
  const t = useCallback((key) => {
    return langObj.t[key] ?? (en[key] ?? key);
  }, [langObj]);

  return (
    <LanguageContext.Provider value={{ language: langValue, setLanguage, t, languages: LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}

/** Compact language picker -- drop it anywhere */
export function LanguageSelector({ className = '' }) {
  const { language, setLanguage, languages } = useLanguage();
  return (
    <select
      value={language}
      onChange={e => setLanguage(e.target.value)}
      className={`field-input text-sm py-2 px-3 rounded-xl ${className}`}
      aria-label="Select language"
    >
      {languages.map(l => (
        <option key={l.value} value={l.value}>{l.label}</option>
      ))}
    </select>
  );
}
